import type { ProjectMetadata } from "@docketrail/contracts";

export interface SubmissionDocInput {
  projectName: string;
  applicationUrl: string;
  repoUrl?: string | null;
  submissionStage: string;
  metadata: ProjectMetadata;
  runId: string;
  generatedAt: string;
}

export function generateSubmissionMarkdown(input: SubmissionDocInput): string {
  const getFieldDisplay = (field: { value: string; confirmedByOwner: boolean } | undefined) => {
    if (!field || !field.value) {
      return "_[Missing / Not provided]_";
    }
    const status = field.confirmedByOwner ? "Verified by owner" : "Needs owner confirmation";
    return `${field.value} _(${status})_`;
  };

  return `# MiniPay Submission Pack — ${input.projectName}

**Generated by DocketRail**
- **Run ID**: \`${input.runId}\`
- **Generated At**: ${input.generatedAt} (UTC)
- **Submission Stage**: ${input.submissionStage.toUpperCase()}

> **Notice**: This document is an assembled submission dossier containing observed evidence and owner-confirmed declarations. It is not an official MiniPay certificate or guarantee of listing.

---

## 1. Application Overview
- **Application URL**: [${input.applicationUrl}](${input.applicationUrl})
- **Repository URL**: ${input.repoUrl ? `[${input.repoUrl}](${input.repoUrl})` : "_[Web-only target, no public repository linked]_"}
- **Application Name**: ${getFieldDisplay(input.metadata.appName)}
- **Category**: ${getFieldDisplay(input.metadata.category)}

## 2. Description
${input.metadata.description?.value || "_[No description provided]_"}

## 3. Contact & Support
- **Contact Email**: ${getFieldDisplay(input.metadata.contactEmail)}
- **Support URL**: ${getFieldDisplay(input.metadata.supportUrl)}
- **Terms of Service**: ${getFieldDisplay(input.metadata.termsUrl)}
- **Privacy Policy**: ${getFieldDisplay(input.metadata.privacyUrl)}

## 4. Brand Assets
- **Icon URL**: ${getFieldDisplay(input.metadata.iconUrl)}

---

_Refer to \`requirements.csv\`, \`network-inventory.csv\`, and \`missing-items.md\` for exhaustive compliance and operational details._
`;
}
